DROP TABLE IF EXISTS libros;
DROP TABLE IF EXISTS autores;
CREATE TABLE autores (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, nombre VARCHAR(100) NOT NULL);
CREATE TABLE libros (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, titulo VARCHAR(150) NOT NULL, isbn VARCHAR(20) NOT NULL UNIQUE, anio_publicacion INT NOT NULL, autor_id BIGINT NOT NULL, CONSTRAINT fk_libro_autor FOREIGN KEY (autor_id) REFERENCES autores(id) ON DELETE CASCADE);
